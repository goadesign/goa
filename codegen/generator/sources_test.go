// This file proves source inspection uses the complete shared generation
// lifecycle without installed protobuf programs or file finalization.
package generator

import (
	"testing"

	"github.com/stretchr/testify/require"
	"goa.design/goa/v3/codegen"
	d "goa.design/goa/v3/dsl"
	"goa.design/goa/v3/eval"
)

// TestSourcesUsesPluginsWithoutProgramsOrFinalizers checks source generation
// and the prepared-root audit after templates execute.
func TestSourcesUsesPluginsWithoutProgramsOrFinalizers(t *testing.T) {
	for _, mutate := range []bool{false, true} {
		name := "valid sources"
		if mutate {
			name = "template mutation rejected"
		}
		t.Run(name, func(t *testing.T) {
			root := codegen.RunDSL(t, sourceDefinition)
			t.Setenv("PATH", t.TempDir())
			registry := newRegistry()
			registry.addCommand("gen", genGeneratorFactories()...)
			finalized := false
			var phases []string
			registry.registerPlugin("source-probe", "gen", pluginNormal, func() Plugin {
				return Plugin{
					Prepare: func(string, []eval.Root) error {
						phases = append(phases, "prepare")
						return nil
					},
					Plan: func(*Plan) error {
						phases = append(phases, "plan")
						return nil
					},
					Generate: func(_ *Plan, files []*codegen.File) ([]*codegen.File, error) {
						phases = append(phases, "generate")
						return append(files, &codegen.File{
							Path: "gen/probe/value.go",
							SectionTemplates: []*codegen.SectionTemplate{{
								Name: "probe", Source: "package probe\nvar Value={{ value }}\n",
								FuncMap: map[string]any{"value": func() int {
									if mutate {
										root.API.Title = "changed by template"
									}
									return 1
								}},
							}},
							FinalizeFunc: func(string) error { finalized = true; return nil },
						}), nil
					},
				}
			})
			output, err := sources("source.test/gen", []eval.Root{root}, registry)
			if mutate {
				require.ErrorContains(t, err, "generated source renders")
				require.Nil(t, output)
				return
			}
			require.NoError(t, err)
			require.Equal(t, []string{"prepare", "plan", "generate"}, phases)
			require.False(t, finalized)
			require.Contains(t, string(output["gen/probe/value.go"]), "var Value = 1")
			require.NotContains(t, output, "gen/goa.json")
			require.NotEmpty(t, output["gen/http/source/server/encode_decode.go"])
			foundProto := false
			for path, content := range output {
				if len(path) > 6 && path[len(path)-6:] == ".proto" {
					foundProto = true
					require.Contains(t, string(content), "service Source")
				}
			}
			require.True(t, foundProto)
		})
	}
}

// sourceDefinition exposes one operation over both HTTP and gRPC.
func sourceDefinition() {
	d.API("sources", func() {})
	d.Service("source", func() {
		d.Method("read", func() {
			d.Payload(func() { d.Field(1, "id", d.String) })
			d.Result(func() { d.Field(1, "value", d.String) })
			d.HTTP(func() { d.GET("/source"); d.Response(d.StatusOK) })
			d.GRPC(func() {})
		})
	})
}

// TestSourcesPreservesPluginVersionNamedOutput checks that source inspection
// adds no command metadata that could overwrite a plugin's generated bytes.
func TestSourcesPreservesPluginVersionNamedOutput(t *testing.T) {
	for _, path := range []string{"gen/goa.json", "gen/GOA.JSON"} {
		t.Run(path, func(t *testing.T) {
			root := codegen.RunDSL(t, sourceDefinition)
			registry := newRegistry()
			registry.addCommand("gen")
			registry.registerPlugin("version-name", "gen", pluginNormal, func() Plugin {
				return Plugin{Generate: func(_ *Plan, files []*codegen.File) ([]*codegen.File, error) {
					return append(files, &codegen.File{
						Path: path,
						SectionTemplates: []*codegen.SectionTemplate{{
							Name: "plugin", Source: `{"plugin":true}`,
						}},
					}), nil
				}}
			})
			output, err := sources("source.test/gen", []eval.Root{root}, registry)
			require.NoError(t, err)
			require.Len(t, output, 1)
			require.Equal(t, []byte(`{"plugin":true}`), output[path])
		})
	}
}
