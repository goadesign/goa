// Package jsonrpc provides constructs and utilities for building JSON-RPC 2.0
// services with Goa. This package contains the core types, client and server
// implementations, and code generation support for services that communicate
// using the JSON-RPC protocol.
//
// JSON-RPC is a stateless, light-weight remote procedure call (RPC) protocol.
// This package implements the JSON-RPC 2.0 specification as defined in
// https://www.jsonrpc.org/specification.
//
// The package supports:
//   - Request/response method calls
//   - Notification requests (fire-and-forget)
//   - Batch requests for multiple calls
//   - Structured error handling with error codes
//   - HTTP, Server-Sent Events (SSE) and WebSocket transports
//
// Code generated by Goa uses this package to create JSON-RPC clients and
// servers that seamlessly integrate with Goa's design-first approach and
// provide type-safe method invocation.
package jsonrpc
