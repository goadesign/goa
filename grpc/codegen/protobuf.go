type (
	// protoBufScope is the scope for protocol buffer attribute types.
	protoBufScope struct {
		scope *codegen.NameScope
	}

	// protoBufGoFieldNames tracks names occupied by generated message methods,
	// fields, and getters while visiting one protobuf message.
	protoBufGoFieldNames map[string]bool
)

const (
	// wrappedField is the name of the single field of the wrapper messages
	// synthesized by wrapAttr for non-object protobuf message types
	// (primitives, arrays and maps).
	wrappedField = "field"
	// wrappedAttrMeta is the meta key set by wrapAttr on the attribute of
	// synthesized wrapper message user types. Its presence is the contract
	// used by isWrappedAttr and unwrapAttr to identify wrapper messages
	// deterministically.
	wrappedAttrMeta = "grpc:wrapped"

	// protoBufGoFieldNameMeta records the Go field name selected by
	// protoc-gen-go after resolving message method and getter conflicts.
	protoBufGoFieldNameMeta = "grpc:protobuf:go:field:name"

	// protoBufReservedNumberMeta and protoBufReservedNameMeta let an owning Goa
	// type preserve removed protobuf tags and field names across regeneration.
	protoBufReservedNumberMeta = "rpc:reserved:number"
	protoBufReservedNameMeta   = "rpc:reserved:name"
)

// Name returns the protocol buffer type name.
func (p *protoBufScope) Name(att *expr.AttributeExpr, pkg string, _, _ bool) string {
	return protoBufGoFullTypeName(att, pkg, p.scope)
}

// Ref returns the protocol buffer type reference.
func (p *protoBufScope) Ref(att *expr.AttributeExpr, pkg string) string {
	return protoBufGoFullTypeRef(att, pkg, p.scope)
}

// Field returns the field name as generated by protocol buffer compiler.
// NOTE: protoc does not care about common initialisms like api -> API so we
// first transform the name into snake case to end up with Api.
func (*protoBufScope) Field(att *expr.AttributeExpr, name string, firstUpper bool) string {
	if expr.IsUnion(att.Type) {
		if fieldName, ok := att.Meta[protoBufGoFieldNameMeta]; ok && len(fieldName) > 0 {
			return fieldName[0]
		}
		name = protoBufUnionName(name, expr.AsUnion(att.Type))
	}
	return protoBufifyAtt(att, codegen.SnakeCase(name), firstUpper)
}

// Scope returns the name scope.
func (p *protoBufScope) Scope() *codegen.NameScope {
	return p.scope
}

// protoBufTypeContext returns a contextual attribute for the protocol buffer type.
func protoBufTypeContext(pkg string, scope *codegen.NameScope, useDefault bool) *codegen.AttributeContext {
	ctx := codegen.NewAttributeContext(false, true, useDefault, pkg, scope)
	ctx.Scope = &protoBufScope{scope: scope}
	return ctx
}

// makeProtoBufMessage ensures the resulting attribute is an object user type so
// that it can be directly mapped to a protobuf type (protobuf messages must
// always be objects). If the given attribute type is a primitive, array, or a
// map, it wraps the given attribute with an object with a single "field"
// attribute. For nested arrays/maps, the inner array/map is wrapped into a
// user type.
func makeProtoBufMessage(att *expr.AttributeExpr, tname string, sd *ServiceData) *expr.AttributeExpr {
	att = expr.DupAtt(att)
	expr.RemovePkgPath(att)
	ut, isut := att.Type.(expr.UserType)
	switch {
	case att.Type == expr.Empty:
		att.Type = &expr.UserTypeExpr{
			TypeName:      tname,
			AttributeExpr: &expr.AttributeExpr{Type: &expr.Object{}},
			UID:           sd.Name + "#" + tname,
		}
		return att
	case expr.IsPrimitive(att.Type):
		wrapAttr(att, tname, true, sd)
		return att
	case isut:
		if expr.IsArray(ut) {
			wrapAttr(att, tname, false, sd)
		}
	case expr.IsArray(att.Type) || expr.IsMap(att.Type):
		wrapAttr(att, tname, false, sd)
	case expr.IsObject(att.Type) || expr.IsUnion(att.Type):
		att.Type = &expr.UserTypeExpr{
			TypeName:      tname,
			AttributeExpr: expr.DupAtt(att),
			UID:           sd.Name + "#" + tname,
		}
	}
	n := ""
	makeProtoBufMessageR(att, &n, sd, make(map[string]struct{}))
	planProtoBufGoFieldNames(att, make(map[string]struct{}))
	return att
}

// makeProtoBufMessageR is the recursive implementation of makeProtoBufMessage.
func makeProtoBufMessageR(att *expr.AttributeExpr, tname *string, sd *ServiceData, seen map[string]struct{}) {
	ut, isut := att.Type.(expr.UserType)

	// handle infinite recursions
	if isut {
		if _, ok := seen[ut.ID()]; ok {
			return
		}
		seen[ut.ID()] = struct{}{}
	}

	wrap := func(att *expr.AttributeExpr, tname string) {
		switch {
		case expr.IsArray(att.Type):
			wrapAttr(att, "ArrayOf"+tname+
				protoBufify(protoBufMessageDef(expr.AsArray(att.Type).ElemType, sd), true, true), true, sd)
		case expr.IsMap(att.Type):
			m := expr.AsMap(att.Type)
			wrapAttr(att, tname+"MapOf"+
				protoBufify(protoBufMessageDef(m.KeyType, sd), true, true)+
				protoBufify(protoBufMessageDef(m.ElemType, sd), true, true), true, sd)
		}
	}

	switch {
	case expr.IsPrimitive(att.Type):
		return
	case isut:
		if expr.IsArray(ut) {
			wrapAttr(ut.Attribute(), ut.Name(), false, sd)
		}
		makeProtoBufMessageR(ut.Attribute(), tname, sd, seen)
	case expr.IsArray(att.Type):
		ar := expr.AsArray(att.Type)
		makeProtoBufMessageR(ar.ElemType, tname, sd, seen)
		wrap(ar.ElemType, *tname)
	case expr.IsMap(att.Type):
		m := expr.AsMap(att.Type)
		makeProtoBufMessageR(m.ElemType, tname, sd, seen)
		wrap(m.ElemType, *tname)
	case expr.IsUnion(att.Type):
		for _, nat := range expr.AsUnion(att.Type).Values {
			makeProtoBufMessageR(nat.Attribute, tname, sd, seen)
		}
	case expr.IsObject(att.Type):
		for _, nat := range *(expr.AsObject(att.Type)) {
			makeProtoBufMessageR(nat.Attribute, tname, sd, seen)
		}
	}
}

// planProtoBufGoFieldNames walks every generated protobuf message and records
// the field names that protoc-gen-go will emit. Transforms consume these names
// instead of independently guessing from one attribute at a time.
func planProtoBufGoFieldNames(att *expr.AttributeExpr, seen map[string]struct{}) {
	if ut, ok := att.Type.(expr.UserType); ok {
		if _, exists := seen[ut.ID()]; exists {
			return
		}
		seen[ut.ID()] = struct{}{}
		planProtoBufGoFieldNames(ut.Attribute(), seen)
		return
	}
	switch {
	case expr.IsArray(att.Type):
		planProtoBufGoFieldNames(expr.AsArray(att.Type).ElemType, seen)
	case expr.IsMap(att.Type):
		planProtoBufGoFieldNames(expr.AsMap(att.Type).ElemType, seen)
	case expr.IsUnion(att.Type):
		planProtoBufUnionGoFieldNames(att.Type.Name(), att, expr.AsUnion(att.Type), seen)
	case expr.IsObject(att.Type):
		usedNames := newProtoBufGoFieldNames()
		for _, nat := range *expr.AsObject(att.Type) {
			if union := expr.AsUnion(nat.Attribute.Type); union != nil {
				planProtoBufUnionMemberGoFieldNames(nat.Name, nat.Attribute, union, usedNames, seen)
				continue
			}
			usedNames.makeUnique(protoBufRawGoFieldName(nat.Attribute, nat.Name), true)
			planProtoBufGoFieldNames(nat.Attribute, seen)
		}
	}
}

// planProtoBufUnionGoFieldNames handles a message whose complete body is one
// union, such as a standalone result type.
func planProtoBufUnionGoFieldNames(name string, att *expr.AttributeExpr, union *expr.Union, seen map[string]struct{}) {
	planProtoBufUnionMemberGoFieldNames(name, att, union, newProtoBufGoFieldNames(), seen)
}

// planProtoBufUnionMemberGoFieldNames flattens oneof members into their
// containing message in declaration order, then reserves the oneof interface
// field after its first member exactly as protoc-gen-go does.
func planProtoBufUnionMemberGoFieldNames(name string, att *expr.AttributeExpr, union *expr.Union, usedNames *protoBufGoFieldNames, seen map[string]struct{}) {
	oneofName, memberNames := protoBufUnionNames(name, union)
	for i, nat := range union.Values {
		usedNames.makeUnique(protoBufify(memberNames[i], true, false), true)
		if i == 0 {
			setProtoBufGoFieldName(
				att,
				usedNames.makeUnique(protoBufify(oneofName, true, false), false),
			)
		}
		planProtoBufGoFieldNames(nat.Attribute, seen)
	}
}

// protoBufRawGoFieldName computes the initial Go name before message-level
// collision resolution.
func protoBufRawGoFieldName(att *expr.AttributeExpr, name string) string {
	return protoBufifyAtt(att, codegen.SnakeCase(name), true)
}

// setProtoBufGoFieldName stores the resolved name on the protobuf-side
// attribute used by generated transforms.
func setProtoBufGoFieldName(att *expr.AttributeExpr, name string) {
	if att.Meta == nil {
		att.Meta = make(expr.MetaExpr)
	}
	att.Meta[protoBufGoFieldNameMeta] = []string{name}
}

// newProtoBufGoFieldNames starts with the method names reserved by
// protoc-gen-go's open-struct API.
func newProtoBufGoFieldNames() *protoBufGoFieldNames {
	names := protoBufGoFieldNames{
		"Reset":               true,
		"String":              true,
		"ProtoMessage":        true,
		"Marshal":             true,
		"Unmarshal":           true,
		"ExtensionRangeArray": true,
		"ExtensionMap":        true,
		"Descriptor":          true,
	}
	return &names
}

// makeUnique appends underscores until the field and its generated getter do
// not conflict with a name already assigned in the message.
func (n *protoBufGoFieldNames) makeUnique(name string, hasGetter bool) string {
	for (*n)[name] || hasGetter && (*n)["Get"+name] {
		name += "_"
	}
	(*n)[name] = true
	(*n)["Get"+name] = hasGetter
	return name
}

// wrapAttr makes the attribute type a user type by wrapping the given
// attribute into an attribute named "field".
func wrapAttr(att *expr.AttributeExpr, tname string, req bool, sd *ServiceData) {
	wrap := func(attr *expr.AttributeExpr) *expr.AttributeExpr {
		res := &expr.AttributeExpr{
			Type: &expr.Object{
				&expr.NamedAttributeExpr{
					Name: wrappedField,
					Attribute: &expr.AttributeExpr{
						Type:       attr.Type,
						Meta:       expr.MetaExpr{"rpc:tag": []string{"1"}},
						Validation: attr.Validation,
					},
				},
			},
			Meta: expr.MetaExpr{wrappedAttrMeta: []string{wrappedField}},
		}
		if req {
			res.Validation = &expr.ValidationExpr{
				Required: []string{wrappedField},
			}
		}
		return res
	}
	switch dt := att.Type.(type) {
	case expr.UserType:
		// Don't change the original user type. Create a copy and wrap that.
		ut := expr.Dup(dt).(expr.UserType)
		ut.SetAttribute(wrap(ut.Attribute()))
		att.Type = ut
	default:
		att.Type = &expr.UserTypeExpr{
			TypeName:      tname,
			AttributeExpr: wrap(att),
			UID:           sd.Name + "#" + tname,
		}
	}
	// Validation is moved to wrapped attribute.
	att.Validation = nil
}

// isWrappedAttr reports whether att references a wrapper message synthesized
// by wrapAttr: att.Type is a user type whose attribute carries the
// wrappedAttrMeta marker. User type chains are followed because wrapAttr
// nests the wrapper user type inside user defined array types (see
// makeProtoBufMessageR).
func isWrappedAttr(att *expr.AttributeExpr) bool {
	ut, ok := att.Type.(expr.UserType)
	if !ok {
		return false
	}
	wrapper := ut.Attribute()
	if len(wrapper.Meta[wrappedAttrMeta]) > 0 {
		return true
	}
	return isWrappedAttr(wrapper)
}

// unwrapAttr returns the attribute wrapped by the wrapper message referenced
// by att as synthesized by wrapAttr. att must either carry the
// wrappedAttrMeta marker directly (it is the wrapper user type attribute
// itself) or reference a (possibly nested) wrapper user type. unwrapAttr
// panics when att is not a wrapper or when the wrapper field is missing:
// both denote a violation of the wrapping contract established at message
// creation.
func unwrapAttr(att *expr.AttributeExpr) *expr.AttributeExpr {
	wrapper := att
	for len(wrapper.Meta[wrappedAttrMeta]) == 0 {
		ut, ok := wrapper.Type.(expr.UserType)
		if !ok {
			panic(fmt.Sprintf("attribute of type %q is not a protobuf wrapper message", att.Type.Name())) // bug
		}
		wrapper = ut.Attribute()
	}
	field := expr.AsObject(wrapper.Type).Attribute(wrappedField)
	if field == nil {
		panic(fmt.Sprintf("protobuf wrapper message of type %q has no %q attribute", att.Type.Name(), wrappedField)) // bug
	}
	return field
}

// protoBufMessageName returns the protocol buffer message name of the given
// attribute type.
func protoBufMessageName(att *expr.AttributeExpr, s *codegen.NameScope) string {
	return protoBufFullMessageName(att, "", s)
}

// protoBufFullMessageName returns the protocol buffer message name of the
// given user type qualified with the given package name if applicable.
func protoBufFullMessageName(att *expr.AttributeExpr, pkg string, s *codegen.NameScope) string {
	switch actual := att.Type.(type) {
	case expr.UserType, *expr.Union:
		n := s.HashedUnique(actual, protoBufify(actual.Name(), true, true), "")
		if name := att.Meta["struct:name:proto"]; len(name) > 0 {
			n = name[0]
		}
		if pkg == "" {
			return n
		}
		return pkg + "." + n
	case expr.CompositeExpr:
		return protoBufFullMessageName(actual.Attribute(), pkg, s)
	default:
		panic(fmt.Sprintf("data type is not a user type or union: received type %T", actual)) // bug
	}
}

// protoBufGoTypeName returns the protocol buffer type name for the given
// attribute generated after compiling the proto file (in *.pb.go).
func protoBufGoTypeName(att *expr.AttributeExpr, s *codegen.NameScope) string {
	return protoBufGoFullTypeName(att, "", s)
}

// protoBufGoFullTypeName returns the protocol buffer type name qualified with
// the given package name for the given attribute generated after compiling
// the proto file (in *.pb.go).
func protoBufGoFullTypeName(att *expr.AttributeExpr, pkg string, s *codegen.NameScope) string {
	if proto := att.Meta["struct:field:proto"]; len(proto) > 2 {
		typ := proto[2]
		if len(att.Meta["struct:field:proto"]) > 3 {
			elems := strings.Split(att.Meta["struct:field:proto"][3], "/")
			typ = elems[len(elems)-1] + "." + typ
		}
		return typ
	}
	switch actual := att.Type.(type) {
	case expr.UserType, expr.CompositeExpr, *expr.Union:
		return protoBufFullMessageName(att, pkg, s)
	case expr.Primitive:
		return protoBufNativeGoTypeName(att.Type)
	case *expr.Array:
		return "[]" + protoBufGoFullTypeRef(actual.ElemType, pkg, s)
	case *expr.Map:
		return fmt.Sprintf("map[%s]%s",
			protoBufGoFullTypeRef(actual.KeyType, pkg, s),
			protoBufGoFullTypeRef(actual.ElemType, pkg, s))
	case *expr.Object:
		return s.GoTypeDef(att, false, false)
	default:
		panic(fmt.Sprintf("unknown data type %T", actual)) // bug
	}
}

// protoType returns the protocol buffer type name for the given attribute.
func protoType(att *expr.AttributeExpr, sd *ServiceData) string {
	if protos := att.Meta["struct:field:proto"]; len(protos) > 0 {
		return protos[0]
	}
	return protoBufMessageDef(att, sd)
}

// protoBufMessageDef returns the protocol buffer code that defines a message
// which matches the data structure definition (the part that comes after
// `message foo`). The message is defined using the proto3 syntax.
func protoBufMessageDef(att *expr.AttributeExpr, sd *ServiceData) string {
	switch actual := att.Type.(type) {
	case expr.Primitive:
		return protoNativeType(att.Type)
	case *expr.Array:
		return "repeated " + protoType(actual.ElemType, sd)
	case *expr.Map:
		return fmt.Sprintf("map<%s, %s>", protoType(actual.KeyType, sd), protoType(actual.ElemType, sd))
	case *expr.Union:
		return protoBufUnionDef(actual.Name(), actual, sd)
	case expr.UserType:
		if actual == expr.Empty {
			return " {}"
		}
		if prim := getPrimitive(att); prim != nil {
			return protoBufMessageDef(prim, sd)
		}
		return protoBufMessageName(att, sd.Scope)
	case *expr.Object:
		var ss []string
		ss = append(ss, " {")
		ss = append(ss, protoBufReservations(att)...)
		for _, nat := range *actual {
			if expr.IsUnion(nat.Attribute.Type) {
				ss = append(ss, protoBufUnionDef(nat.Name, expr.AsUnion(nat.Attribute.Type), sd))
				continue
			}
			var (
				fn   string
				fnum uint64
				typ  string
				opt  string
				desc string
			)
			{
				fn = codegen.SnakeCase(protoBufify(nat.Name, false, false))
				fnum = rpcTag(nat.Attribute)
				if prim := getPrimitive(nat.Attribute); prim != nil {
					typ = protoType(prim, sd)
				} else {
					typ = protoType(nat.Attribute, sd)
				}
				if !att.IsRequired(nat.Name) && expr.IsPrimitive(nat.Attribute.Type) {
					opt = "optional "
				}
				if nat.Attribute.Description != "" {
					desc = codegen.Comment(nat.Attribute.Description) + "\n\t"
				}
			}
			optJSON := protoJSONOption(nat.Attribute)
			ss = append(ss, fmt.Sprintf("\t%s%s%s %s = %d%s;", desc, opt, typ, fn, fnum, optJSON))
		}
		ss = append(ss, "}")
		return strings.Join(ss, "\n")
	default:
		panic(fmt.Sprintf("unknown data type %T", actual)) // bug
	}
}

// protoBufReservations renders removed field numbers and names declared on a
// Goa type. Sorting keeps generated schemas stable when metadata values are
// assembled from multiple design files.
func protoBufReservations(att *expr.AttributeExpr) []string {
	var reservations []string
	if values := att.Meta[protoBufReservedNumberMeta]; len(values) > 0 {
		numbers := make([]uint64, len(values))
		for i, value := range values {
			number, err := strconv.ParseUint(value, 10, 64)
			if err != nil {
				panic(fmt.Sprintf("invalid protobuf reserved field number %q: %v", value, err))
			}
			numbers[i] = number
		}
		slices.Sort(numbers)
		parts := make([]string, len(numbers))
		for i, number := range numbers {
			parts[i] = strconv.FormatUint(number, 10)
		}
		reservations = append(reservations, "\treserved "+strings.Join(parts, ", ")+";")
	}
	if values := att.Meta[protoBufReservedNameMeta]; len(values) > 0 {
		names := slices.Clone(values)
		slices.Sort(names)
		parts := make([]string, len(names))
		for i, name := range names {
			parts[i] = strconv.Quote(name)
		}
		reservations = append(reservations, "\treserved "+strings.Join(parts, ", ")+";")
	}
	return reservations
}

// protoBufUnionDef renders a protobuf oneof using the field name selected by
// its caller. Nested unions pass their containing attribute name so a custom
// service type name cannot rename the protobuf field used by transforms.
// Standalone unions pass their service type name because no field contains them.
func protoBufUnionDef(name string, union *expr.Union, sd *ServiceData) string {
	oneofName, fieldNames := protoBufUnionNames(name, union)
	def := "\toneof " + oneofName + " {"
	for i, nat := range union.Values {
		fn := fieldNames[i]
		fnum := rpcTag(nat.Attribute)
		var typ string
		if prim := getPrimitive(nat.Attribute); prim != nil {
			typ = protoType(prim, sd)
		} else {
			typ = protoType(nat.Attribute, sd)
		}
		var desc string
		if d := nat.Attribute.Description; d != "" {
			desc = codegen.Comment(d) + "\n\t"
		}
		opt := protoJSONOption(nat.Attribute)
		def += fmt.Sprintf("\n\t\t%s%s %s = %d%s;", desc, typ, fn, fnum, opt)
	}
	return def + "\n\t}"
}

// protoBufUnionName returns the oneof name emitted by protoc. When a member
// has the same normalized name, it adds a suffix so protoc can generate both
// the oneof interface field and the member wrapper.
func protoBufUnionName(name string, union *expr.Union) string {
	oneofName, _ := protoBufUnionNames(name, union)
	return oneofName
}

// protoBufUnionNames returns the oneof name and member names emitted by protoc
// so schema generation and transform field access use the same normalization.
func protoBufUnionNames(name string, union *expr.Union) (string, []string) {
	oneofName := codegen.SnakeCase(protoBufify(name, false, false))
	fieldNames := make([]string, len(union.Values))
	for i, nat := range union.Values {
		fieldNames[i] = codegen.SnakeCase(protoBufify(nat.Name, false, false))
	}
	for slices.Contains(fieldNames, oneofName) {
		oneofName += "_oneof"
	}
	return oneofName, fieldNames
}

func protoJSONOption(att *expr.AttributeExpr) string {
	if att == nil || att.Meta == nil {
		return ""
	}
	if names := att.Meta["proto:tag:json"]; len(names) > 0 && names[0] != "" {
		return fmt.Sprintf(" [json_name = %q]", names[0])
	}
	return ""
}

// protoBufGoFullTypeRef returns the Go code qualified with package name that
// refers to the Go type generated by compiling the protocol buffer
// (in *.pb.go) for the given attribute.
func protoBufGoFullTypeRef(att *expr.AttributeExpr, pkg string, s *codegen.NameScope) string {
	name := protoBufGoFullTypeName(att, pkg, s)
	if expr.IsObject(att.Type) || expr.IsUnion(att.Type) {
		return "*" + name
	}
	return name
}

var digits = regexp.MustCompile("[0-9]+")

// protoBufify makes a valid protocol buffer identifier out of any string.
// It does that by removing any non letter and non digit character and by
// making sure the first character is a letter or "_". protoBufify produces a
// "CamelCase" version of the string.
//
// If firstUpper is true the first character of the identifier is uppercase
// otherwise it's lowercase.
func protoBufify(str string, firstUpper, acronym bool) string {
	// Optimize trivial case
	if str == "" {
		return ""
	}

	// Remove optional suffix that defines corresponding transport specific
	// name.
	idx := strings.Index(str, ":")
	if idx > 0 {
		str = str[:idx]
	}

	// The CamelCase implementation of protoc-gen-go considers digits as words
	// but our CamelCase implementation considers them as lower case characters,
	// compensate by adding an underscore after any series of digits.
	// See https://github.com/golang/protobuf/blob/d04d7b157bb510b1e0c10132224b616ac0e26b17/protoc-gen-go/generator/generator.go#L2648-L2685
	str = string(digits.ReplaceAllFunc([]byte(str), func(match []byte) []byte {
		res := make([]byte, len(match)+1) // need to allocate new slice
		copy(res, match)
		res[len(res)-1] = '_'
		return res
	}))

	str = codegen.CamelCase(str, firstUpper, acronym)
	if str == "" {
		// All characters are invalid. Produce a default value.
		if firstUpper {
			return "Val"
		}
		return "val"
	}

	return fixReservedProtoBuf(str)
}

// protoBufifyAtt honors any struct:field:name meta set on the attribute and
// and calls protoBufify with the tag value if present or the given name
// otherwise.
func protoBufifyAtt(att *expr.AttributeExpr, name string, upper bool) string {
	if tname, ok := att.Meta["struct:field:name"]; ok {
		if len(tname) > 0 {
			name = tname[0]
		}
	}
	return protoBufify(name, upper, false)
}

// protoNativeType returns the protocol buffer built-in type
// corresponding to the given primitive type. It panics if t is not a
// primitive type.
func protoNativeType(t expr.DataType) string {
	switch t.Kind() {
	case expr.BooleanKind:
		return "bool"
	case expr.IntKind:
		return "sint32"
	case expr.Int32Kind:
		return "sint32"
	case expr.Int64Kind:
		return "sint64"
	case expr.UIntKind:
		return "uint32"
	case expr.UInt32Kind:
		return "uint32"
	case expr.UInt64Kind:
		return "uint64"
	case expr.Float32Kind:
		return "float"
	case expr.Float64Kind:
		return "double"
	case expr.StringKind:
		return "string"
	case expr.BytesKind:
		return "bytes"
	case expr.AnyKind:
		return "google.protobuf.Value"
	default:
		panic(fmt.Sprintf("cannot compute native protocol buffer type for %T", t)) // bug
	}
}

// protoBufNativeGoTypeName returns the Go type corresponding to the given
// primitive type generated by the protocol buffer compiler after compiling
// the ".proto" file (in *.pb.go).
func protoBufNativeGoTypeName(t expr.DataType) string {
	switch t.Kind() {
	case expr.BooleanKind:
		return "bool"
	case expr.IntKind:
		return "int32"
	case expr.Int32Kind:
		return "int32"
	case expr.Int64Kind:
		return "int64"
	case expr.UIntKind:
		return "uint32"
	case expr.UInt32Kind:
		return "uint32"
	case expr.UInt64Kind:
		return "uint64"
	case expr.Float32Kind:
		return "float32"
	case expr.Float64Kind:
		return "float64"
	case expr.StringKind:
		return "string"
	case expr.BytesKind:
		return "[]byte"
	case expr.AnyKind:
		return "*structpb.Value"
	default:
		panic(fmt.Sprintf("cannot compute native protocol buffer type for %T %v", t, t)) // bug
	}
}

// rpcTag returns the unique numbered RPC tag from the given attribute. Every
// gRPC message field carries a tag by the time codegen runs: DSL validation
// rejects untagged fields and synthesized wrapper fields are tagged at
// creation, so a missing or unparseable tag is a bug.
func rpcTag(a *expr.AttributeExpr) uint64 {
	t, ok := a.FieldTag()
	if !ok {
		panic(fmt.Sprintf("attribute of type %q has no rpc:tag meta", a.Type.Name())) // bug
	}
	tag, err := strconv.ParseUint(t, 10, 64)
	if err != nil {
		panic(err) // bug
	}
	return tag
}

// fixReservedProtoBuf appends an underscore on to protocol buffer reserved
// keywords.
func fixReservedProtoBuf(w string) string {
	if _, ok := reservedProtoBuf[codegen.CamelCase(w, false, false)]; ok {
		w += "_"
	}
	return w
}

